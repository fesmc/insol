#!/usr/bin/env julia
#
# Build the irradiance test fixture from NREL NSRDB station data.
#
# The NSRDB files carry a Solar Zenith Angle computed by NREL's own solar
# position algorithm, alongside measured/modelled GHI, DNI and DHI. That makes
# them an independent reference for both halves of the irradiance module: the
# solar geometry can be checked exactly, and the irradiance decomposition can be
# scored against real values.
#
# The source archive is far too large to commit, so this writes a strided sample
# to tests/reference/. The stride is chosen coprime with the 48 half-hourly
# records per day, so the sample walks through every time of day as it advances
# through the year rather than always landing at the same hour.
#
# Timestamps in NSRDB are local standard time; the fixture also stores the UTC
# hour of the year, which is what the library's solar position routine expects.
#
# Source: National Solar Radiation Database (NSRDB), NREL. Public domain.
#   https://nsrdb.nrel.gov/
#
# Usage:  julia scripts/make_nrel_fixture.jl [nsrdb_dir] [output_file]

using Printf

const STRIDE = 97          # coprime with 48 -> full diurnal coverage
const YEARS  = [2019, 2020]  # one common year, one leap year

"One NSRDB station-year: metadata plus the sampled records."
struct Station
    id::String
    lat::Float64
    lon::Float64
    tz::Float64
end

function read_station_year(path)
    lines = readlines(path)
    length(lines) < 4 && error("unexpected NSRDB file: $path")

    meta = split(lines[2], ',')
    station = Station(meta[2], parse(Float64, meta[6]),
                      parse(Float64, meta[7]), parse(Float64, meta[8]))

    cols = split(lines[3], ',')
    idx = Dict(strip(c) => i for (i, c) in enumerate(cols))
    for required in ("Year","Month","Day","Hour","Minute",
                     "DHI","DNI","GHI","Solar Zenith Angle","Temperature","Pressure")
        haskey(idx, required) || error("column '$required' missing from $path")
    end

    records = []
    for ln in lines[4:end]
        isempty(strip(ln)) && continue
        f = split(ln, ',')
        get_f(name) = parse(Float64, f[idx[name]])
        get_i(name) = parse(Int, f[idx[name]])
        push!(records, (year = get_i("Year"), month = get_i("Month"),
                        day = get_i("Day"), hour = get_i("Hour"),
                        minute = get_i("Minute"),
                        zenith = get_f("Solar Zenith Angle"),
                        ghi = get_f("GHI"), dni = get_f("DNI"),
                        dhi = get_f("DHI"), temp = get_f("Temperature"),
                        pressure = get_f("Pressure")))
    end

    return station, records
end

"Day of the year (1-based) for a calendar date."
function day_of_year(y, m, d)
    leap = (y % 4 == 0 && y % 100 != 0) || y % 400 == 0
    mdays = [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    return sum(mdays[1:m-1]) + d
end

days_in_year(y) = day_of_year(y, 12, 31)

function main()
    nsrdb_dir = length(ARGS) >= 1 ? ARGS[1] :
                joinpath(homedir(), "data", "nrel", "NRELNSRDBViewerData")
    outfile   = length(ARGS) >= 2 ? ARGS[2] : "tests/reference/nrel_stations.txt"

    isdir(nsrdb_dir) || error("NSRDB directory not found: $nsrdb_dir")

    files = sort(filter(f -> endswith(f, ".csv") && occursin("_", f),
                        readdir(nsrdb_dir)))
    isempty(files) && error("no NSRDB csv files in $nsrdb_dir")

    nrows = 0
    open(outfile, "w") do io
        println(io, "# NREL NSRDB station records, for the irradiance tests.")
        println(io, "# Generated by scripts/make_nrel_fixture.jl -- a strided")
        println(io, "# sample of the full archive, which is too large to commit.")
        println(io, "#")
        println(io, "# Source: National Solar Radiation Database (NSRDB), NREL,")
        println(io, "# https://nsrdb.nrel.gov/ -- public domain.")
        println(io, "#")
        println(io, "# `zenith` is NREL's own solar position calculation, used here")
        println(io, "# as an independent reference. Local timestamps are as given in")
        println(io, "# the source (local standard time); hour_utc is derived from")
        println(io, "# them and the station time zone, counting from 0 at 00:00 UTC")
        println(io, "# on 1 January.")
        println(io, "#")
        @printf(io, "#%9s %8s %9s %6s %6s %5s %4s %4s %6s %12s %9s %8s %8s %8s %9s\n",
                "station", "lat", "lon", "tz", "year", "day", "hr", "min",
                "hr_utc", "zenith", "ghi", "dni", "dhi", "temp", "pressure")

        for year in YEARS
            for f in files
                occursin("_$(year).csv", f) || continue
                station, records = read_station_year(joinpath(nsrdb_dir, f))
                ndays = days_in_year(year)

                for k in 1:STRIDE:length(records)
                    r = records[k]
                    doy = day_of_year(r.year, r.month, r.day)

                    # Local standard time -> UTC hour of the year.
                    hour_local = (doy - 1) * 24 + r.hour + r.minute / 60
                    hour_utc   = hour_local - station.tz

                    # Records whose UTC instant falls outside this calendar year
                    # belong to the adjacent one; the fixture has no way to say
                    # so, and comparing them against a within-year hour would be
                    # meaningless. Drop them rather than wrap.
                    (hour_utc < 0 || hour_utc >= 24 * ndays) && continue

                    @printf(io, "%10s %8.2f %9.2f %6.1f %6d %5d %4d %4d %6s %12.4f %9.1f %8.1f %8.1f %8.1f %9.1f\n",
                            station.id, station.lat, station.lon, station.tz,
                            r.year, doy, r.hour, r.minute,
                            @sprintf("%.4f", hour_utc),
                            r.zenith, r.ghi, r.dni, r.dhi, r.temp, r.pressure)
                    nrows += 1
                end
            end
        end
    end

    println("Wrote $nrows records to $outfile")
end

abspath(PROGRAM_FILE) == (@__FILE__) && main()
