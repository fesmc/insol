! Regression tests for the insol library.
!
! Two independent suites:
!
!   1. Reference comparison -- values from tests/reference/insol_reference.txt,
!      generated by scripts/make_reference.jl. That generator is a separate
!      implementation of the Berger (1978) closed-form daily integral and shares
!      no code with this library, so agreement is a genuine cross-check rather
!      than a record of what the library happened to produce.
!
!   2. Physical invariants -- properties the solution must satisfy regardless of
!      how it is computed (non-negativity, polar night, the global energy
!      balance S0/(4 sqrt(1-e^2))). These catch errors a lookup table cannot.
!
! Exits with status 1 if any check fails.

program test_insol

    use insolation

    implicit none

    real(dp), parameter :: pi = 2.0_dp*acos(0.0_dp)

    ! Solar constant and year length assumed by the reference values.
    real(dp), parameter :: S0_ref = 1365.0_dp

    ! Tolerance on the reference comparison. The closed-form daily integral is
    ! exact, so agreement is limited only by round-off in the kind the interface
    ! returns; anything larger indicates a quadrature or interpolation error in
    ! the library. Insolation reaches ~560 W/m2, so one single-precision ulp is
    ! ~7e-5 -- hence the looser bound when built with -DINSOL_SP.
    real(dp), parameter :: tol_ref = merge(1.0e-3_dp, 1.0e-6_dp, wp == sp)

    character(len=*), parameter :: fldr     = "input"
    character(len=*), parameter :: ref_file = "tests/reference/insol_reference.txt"

    integer :: n_pass = 0
    integer :: n_fail = 0

    ! Shared states for point queries, one per supported calendar. Grid-based
    ! checks build their own.
    type(insol_class) :: is, is365

    write(*,*)
    write(*,*) "=============================================="
    write(*,*) " insol regression tests"
    write(*,*) "=============================================="

    call insol_init(is,   fldr=fldr,S0=S0_ref)
    call insol_init(is365,fldr=fldr,S0=S0_ref,day_year=365)

    call test_reference_values()
    call test_equinox_convention()
    call test_interface_consistency()
    call test_non_negative()
    call test_polar_night()
    call test_energy_balance()

    write(*,*)
    write(*,"(a,i0,a,i0,a)") "  ", n_pass, " passed, ", n_fail, " failed"
    write(*,*)

    call insol_end(is)
    call insol_end(is365)

    if (n_fail > 0) then
        write(*,*) "FAILED"
        stop 1
    end if

    write(*,*) "PASSED"

contains

    ! ------------------------------------------------------------------
    ! Suite 1: comparison against independently generated reference values
    ! ------------------------------------------------------------------

    subroutine test_reference_values()

        implicit none

        character(len=512) :: line
        real(dp) :: time_bp, lat, insol_ref, coszm_ref
        real(wp) :: insol
        real(dp) :: err, err_max
        integer  :: day, day_year, io, n, unit

        err_max = 0.0_dp
        n       = 0

        open(newunit=unit,file=ref_file,status="old",iostat=io)
        if (io /= 0) then
            call fail("reference values", "cannot open "//ref_file)
            return
        end if

        do
            read(unit,'(a)',iostat=io) line
            if (io /= 0) exit
            if (len_trim(line) == 0) cycle
            if (line(1:1) == '#') cycle

            read(line,*) time_bp, day_year, lat, day, insol_ref, coszm_ref

            if (day_year == 365) then
                call calc_insol_day(is365,insol,day,lat,time_bp)
            else
                call calc_insol_day(is,insol,day,lat,time_bp)
            end if

            err = abs(insol - insol_ref)
            if (err > err_max) err_max = err
            n = n + 1
        end do

        close(unit)

        if (n == 0) then
            call fail("reference values", "no reference values read")
            return
        end if

        call check("reference values ("//trim(itoa(n))//" points)", &
                   err_max, tol_ref, "max |insol - reference| [W/m2]")

    end subroutine test_reference_values

    subroutine test_equinox_convention()
        ! At an equinox the sun is over the equator, so insolation is symmetric
        ! about it. The solution places the vernal equinox at a fixed fractional
        ! day -- 80.5 of a 360-day year, 79.5 of a 365-day year -- so the
        ! hemispheric asymmetry must change sign between the two integer days
        ! that straddle it.
        !
        ! This is what pins the vernal-equinox convention down: an error in it
        ! shifts the seasons relative to the orbit while leaving both the annual
        ! mean and the reference values self-consistent.

        implicit none

        real(dp) :: asym_before, asym_after

        call calc_asymmetry(is,   80, asym_before)
        call calc_asymmetry(is,   81, asym_after)
        call check_straddle("equinox convention (360-day year)", &
                            asym_before, asym_after)

        call calc_asymmetry(is365, 79, asym_before)
        call calc_asymmetry(is365, 80, asym_after)
        call check_straddle("equinox convention (365-day year)", &
                            asym_before, asym_after)

    end subroutine test_equinox_convention

    subroutine calc_asymmetry(isl,day,asym)
        ! Difference in insolation between 45N and 45S on a given day.

        implicit none

        type(insol_class), intent(IN)  :: isl
        integer,           intent(IN)  :: day
        real(dp),          intent(OUT) :: asym

        ! Local variables
        real(wp) :: insol_n, insol_s

        call calc_insol_day(isl,insol_n,day, 45.0_dp,0.0_dp)
        call calc_insol_day(isl,insol_s,day,-45.0_dp,0.0_dp)

        asym = insol_n - insol_s

    end subroutine calc_asymmetry

    subroutine check_straddle(name,before,after)
        ! Pass if the two values bracket a sign change.

        implicit none

        character(len=*), intent(IN) :: name
        real(dp),         intent(IN) :: before, after

        if (before*after < 0.0_dp) then
            call pass(name)
        else
            call fail(name, "asymmetry does not change sign across the equinox: "// &
                            trim(rtoa(before))//" then "//trim(rtoa(after)))
        end if

    end subroutine check_straddle

    subroutine test_interface_consistency()
        ! The point, vector and 2D interfaces must return the same value for the
        ! same latitude -- they differ only in the shape of their arguments, not
        ! in the physics. Any disagreement means one of them is approximating.
        !
        ! The reference comparison above exercises only the point interface, so
        ! without this check an approximation confined to the array paths (such
        ! as interpolating over a coarse fixed latitude grid) goes unnoticed.

        implicit none

        integer,  parameter :: nlat = 91
        integer,  parameter :: nx = 13, ny = 7
        real(dp) :: lats(nlat)
        real(wp) :: insol_1D(nlat)
        real(dp) :: lats2D(nx,ny)
        real(wp) :: insol_2D(nx,ny)
        real(wp) :: insol_pt
        real(dp) :: err_1D, err_2D
        integer  :: i, j, day
        type(insol_class) :: is1D, is2D

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(is1D,lats,fldr=fldr,S0=S0_ref)

        err_1D = 0.0_dp
        do day = 1, 360, 7
            call calc_insol_day(is1D,insol_1D,day,0.0_dp)
            do i = 1, nlat
                call calc_insol_day(is,insol_pt,day,lats(i),0.0_dp)
                err_1D = max(err_1D, abs(insol_1D(i)-insol_pt))
            end do
        end do

        call insol_end(is1D)

        call check("point vs vector interface", err_1D, tol_ref, &
                   "max |insol_1D - insol_pt| [W/m2]")

        do j = 1, ny
        do i = 1, nx
            lats2D(i,j) = -90.0_dp + (i-1+(j-1)*nx)*180.0_dp/real(nx*ny-1,dp)
        end do
        end do

        call insol_init(is2D,lats2D,fldr=fldr,S0=S0_ref)

        err_2D = 0.0_dp
        do day = 1, 360, 30
            call calc_insol_day(is2D,insol_2D,day,0.0_dp)
            do j = 1, ny
            do i = 1, nx
                call calc_insol_day(is,insol_pt,day,lats2D(i,j),0.0_dp)
                err_2D = max(err_2D, abs(insol_2D(i,j)-insol_pt))
            end do
            end do
        end do

        call insol_end(is2D)

        call check("point vs 2D interface", err_2D, tol_ref, &
                   "max |insol_2D - insol_pt| [W/m2]")

    end subroutine test_interface_consistency

    ! ------------------------------------------------------------------
    ! Suite 2: physical invariants
    ! ------------------------------------------------------------------

    subroutine test_non_negative()
        ! Insolation is a flux onto a horizontal surface: never negative,
        ! and never above the instantaneous solar constant at the sub-solar
        ! point.

        implicit none

        integer,  parameter :: nlat = 181
        real(dp) :: lats(nlat)
        real(wp) :: insol(nlat)
        real(dp) :: worst_low, worst_high
        integer  :: i, day
        type(insol_class) :: isg

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(isg,lats,fldr=fldr,S0=S0_ref)

        worst_low  = 0.0_dp
        worst_high = 0.0_dp

        do day = 1, 360
            call calc_insol_day(isg,insol,day,0.0_dp)
            worst_low  = min(worst_low, minval(insol))
            ! Allow for the Earth-Sun distance factor at perihelion (~3.4%).
            worst_high = max(worst_high, maxval(insol) - 1.05_dp*S0_ref)
        end do

        call insol_end(isg)

        call check("non-negativity", -worst_low, 0.0_dp, "most negative value [W/m2]")
        call check("upper bound",    worst_high, 0.0_dp, "excess over 1.05*S0 [W/m2]")

    end subroutine test_non_negative

    subroutine test_polar_night()
        ! The winter pole receives exactly zero insolation: the sun stays below
        ! the horizon for the whole day, so the daily integral vanishes.

        implicit none

        real(wp) :: insol_n, insol_s

        ! Day 355 is close to the December solstice in a 360-day year, with the
        ! north pole in polar night and the south pole in polar day.
        call calc_insol_day(is, insol_n, 355,  90.0_dp, 0.0_dp)
        call calc_insol_day(is, insol_s, 355, -90.0_dp, 0.0_dp)

        call check("polar night (90N, day 355)", real(insol_n,dp), 0.0_dp, "insolation [W/m2]")

        if (insol_s > 400.0_dp) then
            call pass("polar day (90S, day 355)")
        else
            call fail("polar day (90S, day 355)", "expected > 400 W/m2, got "//trim(rtoa(real(insol_s,dp))))
        end if

    end subroutine test_polar_night

    subroutine test_energy_balance()
        ! The area- and time-averaged insolation over the globe and a full year
        ! must equal S0/(4 sqrt(1-e^2)) exactly -- a consequence of Kepler's
        ! second law, independent of obliquity or perihelion. Averaging uniformly
        ! in sin(latitude) gives the correct area weighting.

        implicit none

        integer,  parameter :: nmu  = 200
        integer,  parameter :: nday = 360
        real(dp), parameter :: ecc_1950 = 0.0167023622549_dp   ! from LA2004 at t=0

        real(dp) :: mu, lats(nmu)
        real(wp) :: insol(nmu)
        real(dp) :: total, mean, expected, rel_err
        integer  :: i, day
        type(insol_class) :: isg

        do i = 1, nmu
            mu = (real(i,dp)-0.5_dp)/real(nmu,dp)*2.0_dp - 1.0_dp
            lats(i) = asin(mu)*180.0_dp/pi
        end do

        call insol_init(isg,lats,fldr=fldr,S0=S0_ref)

        total = 0.0_dp
        do day = 1, nday
            call calc_insol_day(isg,insol,day,0.0_dp)
            total = total + sum(insol)
        end do

        call insol_end(isg)

        mean     = total/real(nday*nmu,dp)
        expected = S0_ref/(4.0_dp*sqrt(1.0_dp-ecc_1950**2))
        rel_err  = abs(mean-expected)/expected

        write(*,"(a,f12.6,a,f12.6)") "     global annual mean = ", mean, &
                                     "  expected = ", expected

        ! Tolerance covers the day/latitude discretization of this check itself.
        call check("global energy balance", rel_err, 1.0e-4_dp, "relative error")

    end subroutine test_energy_balance

    ! ------------------------------------------------------------------
    ! Minimal check framework
    ! ------------------------------------------------------------------

    subroutine check(name, value, tol, what)
        ! Pass if value <= tol.

        implicit none

        character(len=*), intent(IN) :: name, what
        real(dp),         intent(IN) :: value, tol

        ! Phrased as .not.(value <= tol) so that a NaN, which compares false
        ! against everything, is reported as a failure rather than a pass.
        if (.not. (value <= tol)) then
            call fail(name, trim(what)//" = "//trim(rtoa(value))// &
                            " exceeds tolerance "//trim(rtoa(tol)))
        else
            call pass(name)
        end if

    end subroutine check

    subroutine pass(name)

        implicit none

        character(len=*), intent(IN) :: name

        n_pass = n_pass + 1
        write(*,"(a,a)") "  [ ok ] ", name

    end subroutine pass

    subroutine fail(name, reason)

        implicit none

        character(len=*), intent(IN) :: name, reason

        n_fail = n_fail + 1
        write(*,"(a,a)") "  [FAIL] ", name
        write(*,"(a,a)") "         ", reason

    end subroutine fail

    function itoa(i) result(str)

        implicit none

        integer, intent(IN) :: i
        character(len=32)   :: str

        write(str,'(i0)') i

    end function itoa

    function rtoa(x) result(str)

        implicit none

        real(dp), intent(IN) :: x
        character(len=32)    :: str

        write(str,'(es12.4)') x
        str = adjustl(str)

    end function rtoa

end program test_insol
