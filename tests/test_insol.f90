! Regression tests for the insol library.
!
! Two independent suites:
!
!   1. Reference comparison -- values from tests/reference/insol_reference.txt,
!      generated by scripts/make_reference.jl. That generator is a separate
!      implementation of the Berger (1978) closed-form daily integral and shares
!      no code with this library, so agreement is a genuine cross-check rather
!      than a record of what the library happened to produce.
!
!   2. Physical invariants -- properties the solution must satisfy regardless of
!      how it is computed (non-negativity, polar night, the global energy
!      balance S0/(4 sqrt(1-e^2))). These catch errors a lookup table cannot.
!
! Exits with status 1 if any check fails.

program test_insol

    use insolation

    implicit none

    real(dp), parameter :: pi = 2.0_dp*acos(0.0_dp)

    ! Solar constant and year length assumed by the reference values.
    real(dp), parameter :: S0_ref = 1365.0_dp

    ! Tolerance on the reference comparison. The closed-form daily integral is
    ! exact, so agreement is limited only by round-off in the kind the interface
    ! returns; anything larger indicates a quadrature or interpolation error in
    ! the library. Insolation reaches ~560 W/m2, so one single-precision ulp is
    ! ~7e-5 -- hence the looser bound when built with -DINSOL_SP.
    real(dp), parameter :: tol_ref = merge(1.0e-3_dp, 1.0e-6_dp, wp == sp)

    character(len=*), parameter :: fldr     = "input"
    character(len=*), parameter :: ref_file = "tests/reference/insol_reference.txt"

    integer :: n_pass = 0
    integer :: n_fail = 0

    ! Shared states for point queries, one per supported calendar. Grid-based
    ! checks build their own.
    type(insol_class) :: is, is365

    write(*,*)
    write(*,*) "=============================================="
    write(*,*) " insol regression tests"
    write(*,*) "=============================================="

    call insol_init(is,   fldr=fldr,S0=S0_ref)
    call insol_init(is365,fldr=fldr,S0=S0_ref,day_year=365)

    call test_reference_values()
    call test_equinox_convention()
    call test_interface_consistency()
    call test_elevation_threshold()
    call test_diurnal()
    call test_diurnal_interfaces()
    call test_coszm_kind()
    call test_daylength()
    call test_non_negative()
    call test_polar_night()
    call test_energy_balance()
    call test_orbit_pars()

    write(*,*)
    write(*,"(a,i0,a,i0,a)") "  ", n_pass, " passed, ", n_fail, " failed"
    write(*,*)

    call insol_end(is)
    call insol_end(is365)

    if (n_fail > 0) then
        write(*,*) "FAILED"
        stop 1
    end if

    write(*,*) "PASSED"

contains

    ! ------------------------------------------------------------------
    ! Suite 1: comparison against independently generated reference values
    ! ------------------------------------------------------------------

    subroutine test_reference_values()

        implicit none

        character(len=512) :: line
        real(dp) :: time_bp, lat, insol_ref, coszm_ref
        real(wp) :: insol
        real(dp) :: err, err_max
        integer  :: day, day_year, io, n, unit

        err_max = 0.0_dp
        n       = 0

        open(newunit=unit,file=ref_file,status="old",iostat=io)
        if (io /= 0) then
            call fail("reference values", "cannot open "//ref_file)
            return
        end if

        do
            read(unit,'(a)',iostat=io) line
            if (io /= 0) exit
            if (len_trim(line) == 0) cycle
            if (line(1:1) == '#') cycle

            read(line,*) time_bp, day_year, lat, day, insol_ref, coszm_ref

            if (day_year == 365) then
                call calc_insol_day(is365,insol,day,lat,time_bp)
            else
                call calc_insol_day(is,insol,day,lat,time_bp)
            end if

            err = abs(insol - insol_ref)
            if (err > err_max) err_max = err
            n = n + 1
        end do

        close(unit)

        if (n == 0) then
            call fail("reference values", "no reference values read")
            return
        end if

        call check("reference values ("//trim(itoa(n))//" points)", &
                   err_max, tol_ref, "max |insol - reference| [W/m2]")

    end subroutine test_reference_values

    subroutine test_equinox_convention()
        ! At an equinox the sun is over the equator, so insolation is symmetric
        ! about it. The solution places the vernal equinox at a fixed fractional
        ! day -- 80.5 of a 360-day year, 79.5 of a 365-day year -- so the
        ! hemispheric asymmetry must change sign between the two integer days
        ! that straddle it.
        !
        ! This is what pins the vernal-equinox convention down: an error in it
        ! shifts the seasons relative to the orbit while leaving both the annual
        ! mean and the reference values self-consistent.

        implicit none

        real(dp) :: asym_before, asym_after

        call calc_asymmetry(is,   80, asym_before)
        call calc_asymmetry(is,   81, asym_after)
        call check_straddle("equinox convention (360-day year)", &
                            asym_before, asym_after)

        call calc_asymmetry(is365, 79, asym_before)
        call calc_asymmetry(is365, 80, asym_after)
        call check_straddle("equinox convention (365-day year)", &
                            asym_before, asym_after)

    end subroutine test_equinox_convention

    subroutine calc_asymmetry(isl,day,asym)
        ! Difference in insolation between 45N and 45S on a given day.

        implicit none

        type(insol_class), intent(IN)  :: isl
        integer,           intent(IN)  :: day
        real(dp),          intent(OUT) :: asym

        ! Local variables
        real(wp) :: insol_n, insol_s

        call calc_insol_day(isl,insol_n,day, 45.0_dp,0.0_dp)
        call calc_insol_day(isl,insol_s,day,-45.0_dp,0.0_dp)

        asym = insol_n - insol_s

    end subroutine calc_asymmetry

    subroutine check_straddle(name,before,after)
        ! Pass if the two values bracket a sign change.

        implicit none

        character(len=*), intent(IN) :: name
        real(dp),         intent(IN) :: before, after

        if (before*after < 0.0_dp) then
            call pass(name)
        else
            call fail(name, "asymmetry does not change sign across the equinox: "// &
                            trim(rtoa(before))//" then "//trim(rtoa(after)))
        end if

    end subroutine check_straddle

    subroutine test_interface_consistency()
        ! The point, vector and 2D interfaces must return the same value for the
        ! same latitude -- they differ only in the shape of their arguments, not
        ! in the physics. Any disagreement means one of them is approximating.
        !
        ! The reference comparison above exercises only the point interface, so
        ! without this check an approximation confined to the array paths (such
        ! as interpolating over a coarse fixed latitude grid) goes unnoticed.

        implicit none

        integer,  parameter :: nlat = 91
        integer,  parameter :: nx = 13, ny = 7
        real(dp) :: lats(nlat)
        real(wp) :: insol_1D(nlat)
        real(dp) :: lats2D(nx,ny)
        real(wp) :: insol_2D(nx,ny)
        real(wp) :: insol_pt
        real(dp) :: err_1D, err_2D
        integer  :: i, j, day
        type(insol_class) :: is1D, is2D

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(is1D,lats,fldr=fldr,S0=S0_ref)

        err_1D = 0.0_dp
        do day = 1, 360, 7
            call calc_insol_day(is1D,insol_1D,day,0.0_dp)
            do i = 1, nlat
                call calc_insol_day(is,insol_pt,day,lats(i),0.0_dp)
                err_1D = max(err_1D, abs(insol_1D(i)-insol_pt))
            end do
        end do

        call insol_end(is1D)

        call check("point vs vector interface", err_1D, tol_ref, &
                   "max |insol_1D - insol_pt| [W/m2]")

        do j = 1, ny
        do i = 1, nx
            lats2D(i,j) = -90.0_dp + (i-1+(j-1)*nx)*180.0_dp/real(nx*ny-1,dp)
        end do
        end do

        call insol_init(is2D,lats2D,fldr=fldr,S0=S0_ref)

        err_2D = 0.0_dp
        do day = 1, 360, 30
            call calc_insol_day(is2D,insol_2D,day,0.0_dp)
            do j = 1, ny
            do i = 1, nx
                call calc_insol_day(is,insol_pt,day,lats2D(i,j),0.0_dp)
                err_2D = max(err_2D, abs(insol_2D(i,j)-insol_pt))
            end do
            end do
        end do

        call insol_end(is2D)

        call check("point vs 2D interface", err_2D, tol_ref, &
                   "max |insol_2D - insol_pt| [W/m2]")

    end subroutine test_interface_consistency

    subroutine test_elevation_threshold()
        ! calc_insol_day with elev_min restricts the daily integral to the part
        ! of the day when the sun is higher than a given elevation -- what dEBM
        ! (Krebs-Kanzow et al., 2018) needs to resolve the diurnal melt cycle.
        !
        ! Three things must hold. A threshold of zero must reproduce the plain
        ! daily mean exactly, with coszm the all-day flux-weighted mean cosine
        ! that the reference file carries. Raising the threshold can only shorten
        ! the day. And the geometry must survive the poles, where the elevation
        ! is constant through the day.

        implicit none

        character(len=512) :: line
        real(dp) :: time_bp, lat, insol_ref, coszm_ref
        real(wp) :: insol, tday, coszm, insol_plain
        real(dp) :: err_daily, err_coszm, err
        real(dp) :: tday_lo, tday_hi
        real(wp) :: insol_hi, coszm_hi, tday_hi_wp
        integer  :: ilat
        integer  :: day, day_year, io, n, unit
        type(insol_class) :: isl

        ! --- threshold of zero reproduces the plain daily mean and the
        !     reference mean cosine, over every point in the reference table ---
        err_daily = 0.0_dp
        err_coszm = 0.0_dp
        n = 0

        open(newunit=unit,file=ref_file,status="old",iostat=io)
        if (io /= 0) then
            call fail("insol_above vs reference", "cannot open "//ref_file)
            return
        end if

        do
            read(unit,'(a)',iostat=io) line
            if (io /= 0) exit
            if (len_trim(line) == 0) cycle
            if (line(1:1) == '#') cycle

            read(line,*) time_bp, day_year, lat, day, insol_ref, coszm_ref

            if (day_year == 365) then
                call calc_insol_day(is365,insol,day,lat,time_bp,elev_min=0.0_dp, &
                                    tday=tday,coszm=coszm)
                call calc_insol_day(is365,insol_plain,day,lat,time_bp)
            else
                call calc_insol_day(is,insol,day,lat,time_bp,elev_min=0.0_dp, &
                                    tday=tday,coszm=coszm)
                call calc_insol_day(is,insol_plain,day,lat,time_bp)
            end if

            ! With no elevation floor, insol must equal the plain daily mean
            ! exactly, and coszm the reference all-day flux-weighted mean cosine.
            err_daily = max(err_daily, abs(real(insol,dp) - real(insol_plain,dp)))
            err_coszm = max(err_coszm, abs(real(coszm,dp) - coszm_ref))
            n = n + 1
        end do

        close(unit)

        call check("elev_min=0 reproduces the daily mean", err_daily, tol_ref, &
                   "max |insol(elev_min=0) - calc_insol_day| [W/m2]")
        call check("mean cos(zenith) vs reference", err_coszm, tol_ref, &
                   "max |coszm - reference|")

        ! --- raising the threshold shortens the day and cannot lengthen it ---
        call insol_init(isl,fldr=fldr,S0=S0_ref)

        err = 0.0_dp
        do day = 1, 360, 11
            do ilat = -80, 80, 20
                lat = real(ilat,dp)
                call calc_insol_day(isl,insol,   day,lat,0.0_dp,elev_min= 0.0_dp,tday=tday)
                call calc_insol_day(isl,insol_hi,day,lat,0.0_dp,elev_min=20.0_dp,tday=tday_hi_wp)
                tday_lo = real(tday,dp)
                tday_hi = real(tday_hi_wp,dp)
                err = max(err, tday_hi - tday_lo)
            end do
        end do

        call check("higher threshold cannot lengthen the day", err, 0.0_dp, &
                   "max increase in day fraction")

        ! --- poles: the sun holds a constant elevation, so a threshold either
        !     admits the whole day or none of it ---
        call calc_insol_day(isl,insol,172,90.0_dp,0.0_dp,elev_min=10.0_dp,tday=tday)
        call check_exact("north pole, midsummer, 10 deg threshold: sun up all day", &
                         real(tday,dp), 1.0_dp)

        call calc_insol_day(isl,insol,172,90.0_dp,0.0_dp,elev_min=30.0_dp,tday=tday)
        call check_exact("north pole, midsummer, 30 deg threshold: sun never that high", &
                         real(tday,dp), 0.0_dp)

        call calc_insol_day(isl,insol,355,90.0_dp,0.0_dp,elev_min=0.0_dp,tday=tday)
        call check_exact("north pole, polar night: sun never up", real(tday,dp), 0.0_dp)

        call insol_end(isl)

    end subroutine test_elevation_threshold

    subroutine test_diurnal()
        ! The diurnal routine samples the day; the daily mean it returns comes
        ! from the exact closed form. Three things must hold: the sampled cycle
        ! integrates back to that mean as the sampling is refined, the samples
        ! obey the same physical bounds as the daily mean (non-negative, below
        ! the instantaneous solar constant, min <= mean <= max), and the
        ! whole-year `_days` call agrees with the per-day call.

        implicit none

        integer, parameter :: nlat = 46
        integer, parameter :: nh   = 2880          ! 30-second sampling
        real(dp) :: lats(nlat)
        real(wp) :: solar(nlat,nh), cosz(nlat,nh)
        real(wp) :: solarm(nlat), solarmin(nlat), solarmax(nlat), coszm(nlat)
        real(wp) :: mean_sampled
        real(dp) :: err_mean, err_bounds, err_order, err_cosz
        integer  :: i, day
        type(insol_class) :: isg

        ! Days-wrapper cross-check
        integer, parameter :: nd = 4
        integer  :: days(nd)
        real(wp) :: solar3(nlat,nd,nh), cosz3(nlat,nd,nh)
        real(wp) :: solarm2(nlat,nd), solarmin2(nlat,nd)
        real(wp) :: solarmax2(nlat,nd), coszm2(nlat,nd)
        real(dp) :: err_days

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(isg,lats,fldr=fldr,S0=S0_ref)

        err_mean   = 0.0_dp
        err_bounds = 0.0_dp
        err_order  = 0.0_dp
        err_cosz   = 0.0_dp

        do day = 1, 360, 15
            call calc_insol_diurnal(isg,day,0.0_dp,solar,cosz, &
                                    solarm=solarm,solarmin=solarmin, &
                                    solarmax=solarmax,coszm=coszm)
            do i = 1, nlat
                ! Sampled mean must converge to the analytic daily mean.
                mean_sampled = sum(solar(i,:))/real(nh,wp)
                err_mean = max(err_mean, abs(real(mean_sampled-solarm(i),dp)))

                ! Physical bounds on the instantaneous samples.
                err_bounds = max(err_bounds, real(-minval(solar(i,:)),dp))
                err_bounds = max(err_bounds, real(maxval(solar(i,:))-1.05_wp*S0_ref,dp))
                err_bounds = max(err_bounds, real(-minval(cosz(i,:)),dp))
                err_bounds = max(err_bounds, real(maxval(cosz(i,:))-1.0_wp,dp))

                ! Min <= mean <= max.
                err_order = max(err_order, real(solarmin(i)-solarm(i),dp))
                err_order = max(err_order, real(solarm(i)-solarmax(i),dp))

                ! Reported min/max must match the samples they summarize.
                err_cosz = max(err_cosz, real(abs(solarmin(i)-minval(solar(i,:))),dp))
                err_cosz = max(err_cosz, real(abs(solarmax(i)-maxval(solar(i,:))),dp))
            end do
        end do

        call check("diurnal mean integrates to daily mean", err_mean, 5.0e-2_dp, &
                   "max |mean(samples) - solarm| [W/m2]")
        call check("diurnal samples within physical bounds", err_bounds, tol_ref, &
                   "worst bound violation")
        call check("diurnal min <= mean <= max", err_order, tol_ref, &
                   "worst ordering violation [W/m2]")
        call check("diurnal min/max match samples", err_cosz, tol_ref, &
                   "max |reported - sample extreme| [W/m2]")

        ! --- the _days call must reproduce the per-day call exactly ---
        days = [10, 100, 200, 300]
        call calc_insol_diurnal_days(isg,days,0.0_dp,solar3,cosz3, &
                                     solarm=solarm2,solarmin=solarmin2, &
                                     solarmax=solarmax2,coszm=coszm2)

        err_days = 0.0_dp
        do i = 1, nd
            call calc_insol_diurnal(isg,days(i),0.0_dp,solar,cosz, &
                                    solarm=solarm,solarmin=solarmin, &
                                    solarmax=solarmax,coszm=coszm)
            err_days = max(err_days, real(maxval(abs(solar3(:,i,:)-solar)),dp))
            err_days = max(err_days, real(maxval(abs(cosz3(:,i,:)-cosz)),dp))
            err_days = max(err_days, real(maxval(abs(solarm2(:,i)-solarm)),dp))
            err_days = max(err_days, real(maxval(abs(coszm2(:,i)-coszm)),dp))
        end do

        call insol_end(isg)

        call check("diurnal _days matches per-day", err_days, 0.0_dp, &
                   "max |days - per-day|")

    end subroutine test_diurnal

    subroutine test_diurnal_interfaces()
        ! The point, 1D and 2D diurnal interfaces differ only in the shape of
        ! their arguments; they must return identical numbers for the same
        ! latitude. The point form additionally must need no grid, and the 2D
        ! `_days` form must reproduce the 2D per-day form.

        implicit none

        integer, parameter :: nh = 48
        integer, parameter :: nx = 8, ny = 5, nlat = nx*ny
        real(dp) :: lats1D(nlat), lats2D(nx,ny)
        real(wp) :: solar1(nlat,nh), cosz1(nlat,nh)
        real(wp) :: solarm1(nlat), solarmin1(nlat), solarmax1(nlat), coszm1(nlat)
        real(wp) :: solar2(nx,ny,nh), cosz2(nx,ny,nh)
        real(wp) :: solarm2(nx,ny), solarmin2(nx,ny), solarmax2(nx,ny), coszm2(nx,ny)
        real(wp) :: solarp(nh), coszp(nh)
        real(wp) :: solarmp, solarminp, solarmaxp, coszmp
        real(dp) :: err_pt, err_2D
        integer  :: i, j, day, jflat
        type(insol_class) :: is1D, is2D

        ! Days-2D vs 2D per-day
        integer, parameter :: nd = 3
        integer  :: days(nd)
        real(wp) :: solar2d3(nx,ny,nd,nh), cosz2d3(nx,ny,nd,nh)
        real(wp) :: solarm2d3(nx,ny,nd)
        real(dp) :: err_days2D

        do i = 1, nlat
            lats1D(i) = -88.0_dp + (i-1)*176.0_dp/real(nlat-1,dp)
        end do
        lats2D = reshape(lats1D,[nx,ny])

        call insol_init(is1D,lats1D,fldr=fldr,S0=S0_ref)
        call insol_init(is2D,lats2D,fldr=fldr,S0=S0_ref)

        err_pt = 0.0_dp
        err_2D = 0.0_dp

        do day = 20, 340, 40
            call calc_insol_diurnal(is1D,day,0.0_dp,solar1,cosz1, &
                                    solarm=solarm1,solarmin=solarmin1, &
                                    solarmax=solarmax1,coszm=coszm1)
            call calc_insol_diurnal(is2D,day,0.0_dp,solar2,cosz2, &
                                    solarm=solarm2,solarmin=solarmin2, &
                                    solarmax=solarmax2,coszm=coszm2)

            do j = 1, ny
            do i = 1, nx
                jflat = i + (j-1)*nx

                ! 2D vs 1D (same flattened latitude).
                err_2D = max(err_2D, real(maxval(abs(solar2(i,j,:)-solar1(jflat,:))),dp))
                err_2D = max(err_2D, real(maxval(abs(cosz2(i,j,:)-cosz1(jflat,:))),dp))
                err_2D = max(err_2D, real(abs(solarm2(i,j)  -solarm1(jflat)),dp))
                err_2D = max(err_2D, real(abs(solarmin2(i,j)-solarmin1(jflat)),dp))
                err_2D = max(err_2D, real(abs(solarmax2(i,j)-solarmax1(jflat)),dp))
                err_2D = max(err_2D, real(abs(coszm2(i,j)   -coszm1(jflat)),dp))
            end do
            end do

            ! Point form (on the bare state `is`, which has no grid) vs 1D.
            do i = 1, nlat
                call calc_insol_diurnal(is,day,lats1D(i),0.0_dp,solarp,coszp, &
                                        solarm=solarmp,solarmin=solarminp, &
                                        solarmax=solarmaxp,coszm=coszmp)
                err_pt = max(err_pt, real(maxval(abs(solarp-solar1(i,:))),dp))
                err_pt = max(err_pt, real(maxval(abs(coszp -cosz1(i,:))),dp))
                err_pt = max(err_pt, real(abs(solarmp-solarm1(i)),dp))
                err_pt = max(err_pt, real(abs(coszmp -coszm1(i)),dp))
            end do
        end do

        call check("diurnal point vs 1D interface", err_pt, tol_ref, &
                   "max |pt - 1D| [W/m2 or cos]")
        call check("diurnal 2D vs 1D interface", err_2D, tol_ref, &
                   "max |2D - 1D| [W/m2 or cos]")

        ! --- 2D _days reproduces the 2D per-day call ---
        days = [45, 175, 285]
        call calc_insol_diurnal_days(is2D,days,0.0_dp,solar2d3,cosz2d3,solarm=solarm2d3)

        err_days2D = 0.0_dp
        do i = 1, nd
            call calc_insol_diurnal(is2D,days(i),0.0_dp,solar2,cosz2,solarm=solarm2)
            err_days2D = max(err_days2D, real(maxval(abs(solar2d3(:,:,i,:)-solar2)),dp))
            err_days2D = max(err_days2D, real(maxval(abs(cosz2d3(:,:,i,:)-cosz2)),dp))
            err_days2D = max(err_days2D, real(maxval(abs(solarm2d3(:,:,i)-solarm2)),dp))
        end do

        call insol_end(is1D)
        call insol_end(is2D)

        call check("diurnal 2D _days matches 2D per-day", err_days2D, 0.0_dp, &
                   "max |days - per-day|")

    end subroutine test_diurnal_interfaces

    subroutine test_coszm_kind()
        ! coszm_kind selects how the mean cosine of the zenith angle is defined.
        ! "flux" (the default) weights by insolation; "daytime" is the plain mean
        ! over the daylit hours. The two must differ, the default must stay flux,
        ! and each must match an independent estimate: flux from calc_insol_day,
        ! daytime from averaging the sub-daily cosz samples over the daylit part.

        implicit none

        integer, parameter :: nlat = 46
        integer, parameter :: nh   = 2880
        real(dp) :: lats(nlat)
        real(wp) :: solar(nlat,nh), cosz(nlat,nh)
        real(wp) :: coszm_day(nlat)
        real(wp) :: coszm_flux, coszm_dp, insol_pt
        real(wp) :: sum_cz
        integer  :: i, k, day, ndaylit
        real(dp) :: err_daytime, max_diff, avg_sampled
        type(insol_class) :: is_flux, is_day

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(is_flux,lats,fldr=fldr,S0=S0_ref)                       ! default
        call insol_init(is_day, lats,fldr=fldr,S0=S0_ref,coszm_kind="daytime")

        ! --- the two conventions must give distinguishable values ---
        max_diff = 0.0_dp
        do day = 1, 360, 15
            do i = 1, nlat
                call calc_insol_day(is_flux,insol_pt,day,lats(i),0.0_dp, &
                                    elev_min=0.0_dp,coszm=coszm_flux)
                call calc_insol_day(is_day,insol_pt,day,lats(i),0.0_dp, &
                                    elev_min=0.0_dp,coszm=coszm_dp)
                max_diff = max(max_diff, abs(real(coszm_flux-coszm_dp,dp)))
            end do
        end do

        if (max_diff > 1.0e-3_dp) then
            call pass("flux and daytime coszm differ")
        else
            call fail("flux and daytime coszm differ", &
                      "the two conventions gave indistinguishable values")
        end if

        ! --- daytime coszm equals the mean of the daylit cosz samples ---
        err_daytime = 0.0_dp
        do day = 30, 330, 30
            call calc_insol_diurnal(is_day,day,0.0_dp,solar,cosz,coszm=coszm_day)
            do i = 1, nlat
                sum_cz  = 0.0_wp
                ndaylit = 0
                do k = 1, nh
                    if (cosz(i,k) > 0.0_wp) then
                        sum_cz  = sum_cz + cosz(i,k)
                        ndaylit = ndaylit + 1
                    end if
                end do
                if (ndaylit > 0) then
                    avg_sampled = real(sum_cz,dp)/real(ndaylit,dp)
                    err_daytime = max(err_daytime, abs(avg_sampled-real(coszm_day(i),dp)))
                end if
            end do
        end do

        call insol_end(is_flux)
        call insol_end(is_day)

        call check("daytime coszm equals daylit-sample mean", err_daytime, 2.0e-3_dp, &
                   "max |coszm - mean(daylit cosz)|")

    end subroutine test_coszm_kind

    subroutine test_daylength()
        ! Daylength is the plain daily window, so it must equal 24*tday from the
        ! elevation-threshold path exactly, be symmetric about the equator at the
        ! equinox (~12 h everywhere), and take the values 24 and 0 at a summer and
        ! winter pole. The point, vector and 2D interfaces must agree.

        implicit none

        integer, parameter :: nlat = 46
        real(dp) :: lats(nlat)
        real(wp) :: dl(nlat), dl_pt, insol_pt, tday_pt
        real(dp) :: err_tday, err_equinox
        integer  :: i, day
        type(insol_class) :: isg
        real(dp), parameter :: lats2D_flat(6) = [-60.0_dp,-30.0_dp,0.0_dp, &
                                                  30.0_dp, 60.0_dp, 80.0_dp]
        real(dp) :: lats2D(3,2)
        real(wp) :: dl2D(3,2)
        real(dp) :: err_2D

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(isg,lats,fldr=fldr,S0=S0_ref)

        ! --- daylength == 24*tday, and vector == point ---
        err_tday = 0.0_dp
        do day = 1, 360, 13
            call calc_daylength(isg,dl,day,0.0_dp)
            do i = 1, nlat
                call calc_insol_day(is,insol_pt,day,lats(i),0.0_dp, &
                                    elev_min=0.0_dp,tday=tday_pt)
                err_tday = max(err_tday, abs(real(dl(i),dp)-24.0_dp*real(tday_pt,dp)))
                call calc_daylength(isg,dl_pt,day,lats(i),0.0_dp)
                err_tday = max(err_tday, abs(real(dl(i)-dl_pt,dp)))
            end do
        end do

        call check("daylength == 24*tday, vector == point", err_tday, tol_ref, &
                   "max |daylength - 24*tday| [h]")

        ! --- equinox: ~12 h at every latitude (day 80 straddles the equinox) ---
        call calc_daylength(isg,dl,80,0.0_dp)
        err_equinox = 0.0_dp
        do i = 1, nlat
            if (abs(lats(i)) <= 85.0_dp) &
                err_equinox = max(err_equinox, abs(real(dl(i),dp)-12.0_dp))
        end do
        call check("equinox daylength ~12 h", err_equinox, 0.5_dp, &
                   "max |daylength - 12| away from the poles [h]")

        ! --- poles ---
        call calc_daylength(isg,dl_pt,172, 90.0_dp,0.0_dp)
        call check_exact("north pole midsummer daylength = 24 h", real(dl_pt,dp), 24.0_dp)
        call calc_daylength(isg,dl_pt,172,-90.0_dp,0.0_dp)
        call check_exact("south pole, north midsummer daylength = 0 h", real(dl_pt,dp), 0.0_dp)

        call insol_end(isg)

        ! --- 2D interface agrees with the point interface ---
        lats2D = reshape(lats2D_flat,[3,2])
        call insol_init(isg,lats2D,fldr=fldr,S0=S0_ref)
        call calc_daylength(isg,dl2D,120,0.0_dp)
        err_2D = 0.0_dp
        do i = 1, 6
            call calc_daylength(is,dl_pt,120,lats2D_flat(i),0.0_dp)
            err_2D = max(err_2D, abs(real(dl2D(mod(i-1,3)+1,(i-1)/3+1)-dl_pt,dp)))
        end do
        call insol_end(isg)

        call check("daylength point vs 2D interface", err_2D, tol_ref, &
                   "max |dl_2D - dl_pt| [h]")

    end subroutine test_daylength

    ! ------------------------------------------------------------------
    ! Suite 2: physical invariants
    ! ------------------------------------------------------------------

    subroutine test_non_negative()
        ! Insolation is a flux onto a horizontal surface: never negative,
        ! and never above the instantaneous solar constant at the sub-solar
        ! point.

        implicit none

        integer,  parameter :: nlat = 181
        real(dp) :: lats(nlat)
        real(wp) :: insol(nlat)
        real(dp) :: worst_low, worst_high
        integer  :: i, day
        type(insol_class) :: isg

        do i = 1, nlat
            lats(i) = -90.0_dp + (i-1)*180.0_dp/real(nlat-1,dp)
        end do

        call insol_init(isg,lats,fldr=fldr,S0=S0_ref)

        worst_low  = 0.0_dp
        worst_high = 0.0_dp

        do day = 1, 360
            call calc_insol_day(isg,insol,day,0.0_dp)
            worst_low  = min(worst_low, minval(insol))
            ! Allow for the Earth-Sun distance factor at perihelion (~3.4%).
            worst_high = max(worst_high, maxval(insol) - 1.05_dp*S0_ref)
        end do

        call insol_end(isg)

        call check("non-negativity", -worst_low, 0.0_dp, "most negative value [W/m2]")
        call check("upper bound",    worst_high, 0.0_dp, "excess over 1.05*S0 [W/m2]")

    end subroutine test_non_negative

    subroutine test_polar_night()
        ! The winter pole receives exactly zero insolation: the sun stays below
        ! the horizon for the whole day, so the daily integral vanishes.

        implicit none

        real(wp) :: insol_n, insol_s

        ! Day 355 is close to the December solstice in a 360-day year, with the
        ! north pole in polar night and the south pole in polar day.
        call calc_insol_day(is, insol_n, 355,  90.0_dp, 0.0_dp)
        call calc_insol_day(is, insol_s, 355, -90.0_dp, 0.0_dp)

        call check("polar night (90N, day 355)", real(insol_n,dp), 0.0_dp, "insolation [W/m2]")

        if (insol_s > 400.0_dp) then
            call pass("polar day (90S, day 355)")
        else
            call fail("polar day (90S, day 355)", "expected > 400 W/m2, got "//trim(rtoa(real(insol_s,dp))))
        end if

    end subroutine test_polar_night

    subroutine test_energy_balance()
        ! The area- and time-averaged insolation over the globe and a full year
        ! must equal S0/(4 sqrt(1-e^2)) exactly -- a consequence of Kepler's
        ! second law, independent of obliquity or perihelion. Averaging uniformly
        ! in sin(latitude) gives the correct area weighting.

        implicit none

        integer,  parameter :: nmu  = 200
        integer,  parameter :: nday = 360
        real(dp), parameter :: ecc_1950 = 0.0167023622549_dp   ! from LA2004 at t=0

        real(dp) :: mu, lats(nmu)
        real(wp) :: insol(nmu)
        real(dp) :: total, mean, expected, rel_err
        integer  :: i, day
        type(insol_class) :: isg

        do i = 1, nmu
            mu = (real(i,dp)-0.5_dp)/real(nmu,dp)*2.0_dp - 1.0_dp
            lats(i) = asin(mu)*180.0_dp/pi
        end do

        call insol_init(isg,lats,fldr=fldr,S0=S0_ref)

        total = 0.0_dp
        do day = 1, nday
            call calc_insol_day(isg,insol,day,0.0_dp)
            total = total + sum(insol)
        end do

        call insol_end(isg)

        mean     = total/real(nday*nmu,dp)
        expected = S0_ref/(4.0_dp*sqrt(1.0_dp-ecc_1950**2))
        rel_err  = abs(mean-expected)/expected

        write(*,"(a,f12.6,a,f12.6)") "     global annual mean = ", mean, &
                                     "  expected = ", expected

        ! Tolerance covers the day/latitude discretization of this check itself.
        call check("global energy balance", rel_err, 1.0e-4_dp, "relative error")

    end subroutine test_energy_balance

    subroutine test_orbit_pars()
        ! The routines take the orbital elements in place of time_bp, from the
        ! tables (orbit_pars_at) or given (orbit_pars_fixed). Elements read from
        ! the tables at a time must reproduce the time_bp call bit-for-bit, and
        ! so must the same elements passed in as a fixed orbit: both run through
        ! one geometry. A fixed present-day orbit must give the familiar
        ! present-day values, and a circular, untilted orbit the trivial ones.

        implicit none

        integer,  parameter :: nt = 6, nlat = 13
        real(dp), parameter :: times(nt) = [-125e3_dp, -40e3_dp, -21e3_dp, &
                                            -6e3_dp, 0.0_dp, 2.5e4_dp]
        real(dp) :: lats(nlat)
        real(wp) :: a, b, c
        real(wp) :: a1D(nlat,360), b1D(nlat,360), c1D(nlat,360)
        real(wp) :: dl_a(nlat), dl_b(nlat), ave_a(nlat), ave_b(nlat)
        real(dp) :: err_tab, err_fix, err, lat
        integer  :: i, k, day, days(360)
        type(orbit_pars_class) :: orb_t, orb_f
        type(insol_class) :: isg, isg365
        real(wp) :: insol_fix, insol_tab

        do i = 1, nlat
            lats(i) = -90.0_dp + 15.0_dp*(i-1)
        end do
        do day = 1, 360
            days(day) = day
        end do

        call insol_init(isg,   lats,fldr=fldr,S0=S0_ref)
        call insol_init(isg365,lats,fldr=fldr,S0=S0_ref,day_year=365)

        ! --- table and fixed elements reproduce the time_bp call exactly ---
        err_tab = 0.0_dp
        err_fix = 0.0_dp
        do k = 1, nt
            orb_t = orbit_pars_at(is,times(k))
            orb_f = orbit_pars_fixed(orb_t%ecc,orb_t%obl,orb_t%per)

            do day = 1, 360, 7
                do i = 1, nlat
                    call calc_insol_day(is,a,day,lats(i),times(k))
                    call calc_insol_day(is,b,day,lats(i),orb_t)
                    call calc_insol_day(is,c,day,lats(i),orb_f)
                    err_tab = max(err_tab, abs(real(b,dp)-real(a,dp)))
                    err_fix = max(err_fix, abs(real(c,dp)-real(a,dp)))
                end do
            end do

            ! Grid, multi-day, average and daylength paths, in both calendars.
            call calc_insol_days(isg,a1D,days,times(k))
            call calc_insol_days(isg,b1D,days,orb_t)
            call calc_insol_days(isg,c1D,days,orb_f)
            err_tab = max(err_tab, maxval(abs(real(b1D,dp)-real(a1D,dp))))
            err_fix = max(err_fix, maxval(abs(real(c1D,dp)-real(a1D,dp))))

            call calc_insol_days(isg365,a1D,days,times(k))
            call calc_insol_days(isg365,c1D,days,orb_f)
            err_fix = max(err_fix, maxval(abs(real(c1D,dp)-real(a1D,dp))))

            call calc_insol_ave(isg,ave_a,[152,243],times(k))
            call calc_insol_ave(isg,ave_b,[152,243],orb_f)
            err_fix = max(err_fix, maxval(abs(real(ave_b,dp)-real(ave_a,dp))))

            call calc_daylength(isg,dl_a,172,times(k))
            call calc_daylength(isg,dl_b,172,orb_f)
            err_fix = max(err_fix, maxval(abs(real(dl_b,dp)-real(dl_a,dp))))
        end do

        call check("orbit_pars_at reproduces time_bp", err_tab, 0.0_dp, &
                   "max |insol(orbit) - insol(time_bp)| [W/m2]")
        call check("orbit_pars_fixed reproduces time_bp", err_fix, 0.0_dp, &
                   "max |insol(fixed) - insol(time_bp)| [W/m2]")

        ! --- fixed present-day orbit: 65N at the June solstice (day 172 of the
        !     360-day year), close to the table orbit of 1950 ---
        orb_f = orbit_pars_fixed(0.0167_dp,23.44_dp,102.7_dp)
        call calc_insol_day(is,insol_fix,172,65.0_dp,orb_f)
        call calc_insol_day(is,insol_tab,172,65.0_dp,0.0_dp)

        write(*,"(a,f10.4,a,f10.4,a)") "     65N day 172: fixed orbit = ", insol_fix, &
                                       ",  table at 1950 = ", insol_tab, " W/m2"

        call check_range("fixed present-day orbit, 65N June", real(insol_fix,dp), &
                         470.0_dp, 490.0_dp)
        call check("fixed present-day orbit vs table at 1950", &
                   abs(real(insol_fix,dp)-real(insol_tab,dp)), 0.5_dp, &
                   "|insol(fixed) - insol(time_bp=0)| [W/m2]")

        ! --- circular, untilted orbit: the sun stands over the equator every
        !     day at the same distance, so the equator receives S0/pi and the
        !     insolation is symmetric about it ---
        orb_f = orbit_pars_fixed(0.0_dp,0.0_dp,0.0_dp)
        err = 0.0_dp
        do day = 1, 360, 5
            call calc_insol_day(is,a,day,0.0_dp,orb_f)
            err = max(err, abs(real(a,dp)-S0_ref/pi))
            do i = 1, 8
                lat = 10.0_dp*i
                call calc_insol_day(is,b,day, lat,orb_f)
                call calc_insol_day(is,c,day,-lat,orb_f)
                err = max(err, abs(real(b,dp)-real(c,dp)))
            end do
        end do

        call check("circular untilted orbit: equator S0/pi, symmetric", err, tol_ref, &
                   "max error [W/m2]")

        call insol_end(isg)
        call insol_end(isg365)

    end subroutine test_orbit_pars

    ! ------------------------------------------------------------------
    ! Minimal check framework
    ! ------------------------------------------------------------------

    subroutine check(name, value, tol, what)
        ! Pass if value <= tol.

        implicit none

        character(len=*), intent(IN) :: name, what
        real(dp),         intent(IN) :: value, tol

        ! Phrased as .not.(value <= tol) so that a NaN, which compares false
        ! against everything, is reported as a failure rather than a pass.
        if (.not. (value <= tol)) then
            call fail(name, trim(what)//" = "//trim(rtoa(value))// &
                            " exceeds tolerance "//trim(rtoa(tol)))
        else
            call pass(name)
        end if

    end subroutine check

    subroutine check_exact(name, value, expected)

        implicit none

        character(len=*), intent(IN) :: name
        real(dp),         intent(IN) :: value, expected

        if (.not. (abs(value-expected) <= 1.0e-12_dp)) then
            call fail(name, "got "//trim(rtoa(value))//", expected "//trim(rtoa(expected)))
        else
            call pass(name)
        end if

    end subroutine check_exact

    subroutine check_range(name, value, lo, hi)
        ! Pass if lo <= value <= hi.

        implicit none

        character(len=*), intent(IN) :: name
        real(dp),         intent(IN) :: value, lo, hi

        if (.not. (value >= lo .and. value <= hi)) then
            call fail(name, trim(rtoa(value))//" outside ["// &
                            trim(rtoa(lo))//","//trim(rtoa(hi))//"]")
        else
            call pass(name)
        end if

    end subroutine check_range

    subroutine pass(name)

        implicit none

        character(len=*), intent(IN) :: name

        n_pass = n_pass + 1
        write(*,"(a,a)") "  [ ok ] ", name

    end subroutine pass

    subroutine fail(name, reason)

        implicit none

        character(len=*), intent(IN) :: name, reason

        n_fail = n_fail + 1
        write(*,"(a,a)") "  [FAIL] ", name
        write(*,"(a,a)") "         ", reason

    end subroutine fail

    function itoa(i) result(str)

        implicit none

        integer, intent(IN) :: i
        character(len=32)   :: str

        write(str,'(i0)') i

    end function itoa

    function rtoa(x) result(str)

        implicit none

        real(dp), intent(IN) :: x
        character(len=32)    :: str

        write(str,'(es12.4)') x
        str = adjustl(str)

    end function rtoa

end program test_insol
